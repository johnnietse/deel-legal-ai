    # Quick demo
    verifier = ResponseVerifier()

    test_sources = [
        {
            "citation": "Sagaz v. 671122 Ontario, [2001] 2 SCR 983",
            "excerpt": (
                "The central question is whether the person who has been "
                "engaged to perform the services is performing them as a "
                "person in business on his own account. Factors include "
                "control, ownership of tools, chance of profit, and risk of loss."
            ),
        }
    ]

    test_answer = (
        "The Sagaz test asks whether the person is in business on his own account. "
        "The Supreme Court also mandated a strict 5-part checklist that must be "
        "passed in exact order, and the test only applies in Ontario."
    )

    print("Testing verification on a partially hallucinated answer...\n")
    result = verifier.verify_grounding(test_answer, test_sources)
    print(json.dumps(result.to_dict(), indent=2))
